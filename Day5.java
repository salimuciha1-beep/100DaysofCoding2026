public class Day5 {

    public static void main(String[] args) {
        float bb = 80.3f;
        double tb = 170.3;

        System.out.println("berat badan  : " + bb);
        System.out.println("tinggi badan : " + tb);

        //float biasa dugunakan ketika bilangan pecahannya rendah dan akhiranya harus ada huruh f karena supaya bisa terbaca sebagai float
        //double ini tipe data yang sering digunakan ketika kita ingin menampilkan desimal tanpa harus menambahkan sesuatu seperti float.
    }
}
